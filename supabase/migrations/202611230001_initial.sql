create table if not exists users (
  id integer generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  role text not null default 'owner'
);

create table if not exists sessions (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamp with time zone not null
);

create table if not exists tracks (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  title text not null,
  artist text,
  album text,
  year integer,
  genre text,
  duration integer,
  sha256 text not null,
  file_name text not null,
  stored_path text not null,
  mime_type text not null,
  created_at timestamptz not null default now()
);

create index if not exists tracks_owner_idx on tracks(user_id);
create index if not exists tracks_sha256_idx on tracks(user_id, sha256);

create table if not exists playlists (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  name text not null
);

create table if not exists playlist_tracks (
  id integer generated by default as identity primary key,
  playlist_id integer not null references playlists(id) on delete cascade,
  track_id integer not null references tracks(id) on delete cascade,
  position integer not null
);

create table if not exists favorites (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  track_id integer not null references tracks(id) on delete cascade,
  unique(user_id, track_id)
);

-- Application tables are accessed only by the Render/FastAPI backend using
-- the service-role connection. Browser clients must never receive REST access.
alter table users enable row level security;
alter table sessions enable row level security;
alter table tracks enable row level security;
alter table playlists enable row level security;
alter table playlist_tracks enable row level security;
alter table favorites enable row level security;

alter table users force row level security;
alter table sessions force row level security;
alter table tracks force row level security;
alter table playlists force row level security;
alter table playlist_tracks force row level security;
alter table favorites force row level security;

revoke all on users, sessions, tracks, playlists, playlist_tracks, favorites
  from anon, authenticated;

-- Keep music private. The backend authorizes access and streams objects
-- itself; no public Supabase Storage policy is created.
insert into storage.buckets (id, name, public)
values ('music', 'music', false)
on conflict (id) do update set public = false;
